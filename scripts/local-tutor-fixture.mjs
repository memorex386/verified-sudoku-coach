import fs from "node:fs";
import { pathToFileURL } from "node:url";
import path from "node:path";
import { canonicalJson, createTopology, createPuzzle, createBoard, applyPlayerAction } from "@verified-sudoku/domain";
import { proposeSingle, verifySingle, readVerifiedSingle } from "@verified-sudoku/proof-engine";
import { generateCandidate, countSolutions } from "../packages/testing/dist/index.js";
import { fromRoot } from "./lib/project.mjs";

export function localFixture() {
  for (let attempt = 0; attempt <= 999999; attempt++) {
    const candidate = generateCandidate(`vsc-fixture/v1:${attempt}`);
    if (countSolutions(candidate.grid) !== 1) continue;
    const givens = [...candidate.grid].flatMap((d, i) => d === "0" ? [] :
      [{ cellId: `r${Math.floor(i / 9) + 1}c${i % 9 + 1}`, digit: Number(d) }]);
    const puzzle = createPuzzle(createTopology(9), givens);
    let board = createBoard(puzzle, 0, [], []);
    for (let step = 0; step < 81; step++) {
      const found = proposeSingle(board);
      if (found.type !== "proposal") break;
      const capability = verifySingle(board, found.proposal);
      const fact = capability && readVerifiedSingle(board, capability);
      if (!fact) throw new Error("local-fixture-verification");
      const result = applyPlayerAction(board, board.revision, board.stateFingerprint,
        { type: "place-value", cellId: fact.cellId, digit: fact.digit });
      if (result.type !== "accepted") throw new Error("local-fixture-action");
      board = result.board;
    }
    if (proposeSingle(board).type !== "solved") continue;
    return { schemaId: "vsc.puzzle-definition", version: 1, puzzleId: "puz_localtutor000001",
      topology: puzzle.topology, givens, puzzleFingerprint: puzzle.puzzleFingerprint,
      provenance: { kind: "generated", generatorId: "classic-symmetric", generatorVersion: "1.0.0", seed: candidate.seed } };
  }
  throw new Error("local-fixture-exhausted");
}

export function checkLocalFixture(write = false) {
  const puzzle = localFixture();
  const source = `// Generated by scripts/local-tutor-fixture.mjs; local tutor only, not showcase-v1.\nexport const localPuzzle = ${JSON.stringify(canonicalJson(puzzle))};\n`;
  const file = fromRoot("apps/replay-web/src/local-puzzle.ts");
  if (write) fs.writeFileSync(file, source);
  else if (fs.readFileSync(file, "utf8") !== source) throw new Error("local-fixture-drift");
  return puzzle;
}
if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  const fixture = checkLocalFixture(process.argv.includes("--write"));
  console.log(`Local fixture ${fixture.provenance.seed}: ${fixture.givens.length} givens; uniqueness and singles regeneration passed.`);
}
